import { readFileSync } from 'node:fs';
import { computeH0 } from '../../../../src/lib/tda/index.ts';
import type { H0Result } from '../../../../src/lib/tda/index.ts';
import { decodeGrid } from '../../../../src/lib/viz/explorer/data.ts';
import type { BarcodeFile, ColoradoMeta } from '../../../../src/lib/viz/explorer/types.ts';

/** The committed Colorado data files, read once per test file. */
const DIR = 'public/data/colorado/';

export const gridBytes: Buffer = readFileSync(DIR + 'grid.f32');
export const gridBuffer: ArrayBuffer = gridBytes.buffer.slice(
  gridBytes.byteOffset,
  gridBytes.byteOffset + gridBytes.byteLength,
) as ArrayBuffer;
export const meta = JSON.parse(readFileSync(DIR + 'meta.json', 'utf8')) as ColoradoMeta;
export const barcode = JSON.parse(readFileSync(DIR + 'barcode.json', 'utf8')) as BarcodeFile;
export const attributionMd = readFileSync(DIR + 'ATTRIBUTION.md', 'utf8');
export const heights: Float32Array = decodeGrid(gridBuffer);

let cached: H0Result | null = null;
export function liveResult(): H0Result {
  cached ??= computeH0(heights, meta.width, meta.height, { connectivity: 4 });
  return cached;
}

export interface DocLake {
  rank: number;
  persistence: string;
  birth: string;
  birthCell: number;
  birthWhere: string;
  death: string;
  deathCell: number;
  deathWhere: string;
  into: number;
}

/**
 * docs/data.md's "Longest-lived lakes" table (generated by the pipeline from the committed files,
 * pasted unedited), parsed rather than retyped.
 */
export function docLakes(): DocLake[] {
  const md = readFileSync('docs/data.md', 'utf8');
  const start = md.indexOf('## Longest-lived lakes');
  const section = md.slice(start, md.indexOf('### Geography check', start));
  const rows: DocLake[] = [];
  for (const line of section.split('\n')) {
    const c = line.split('|').map((x) => x.trim());
    if (c.length < 11 || !/^\d+$/.test(c[1])) continue;
    rows.push({
      rank: Number(c[1]),
      persistence: c[2],
      birth: c[3],
      birthCell: Number(c[4]),
      birthWhere: c[5],
      death: c[6],
      deathCell: Number(c[7]),
      deathWhere: c[8],
      into: Number(c[9]),
    });
  }
  return rows;
}
